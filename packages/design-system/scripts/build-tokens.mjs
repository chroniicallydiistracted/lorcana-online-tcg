// Builds deterministic token outputs (standard §10) with Style Dictionary 5.6.0 resolving the documented DTCG subset.
// Usage: node scripts/build-tokens.mjs [outputDir]   (default src/generated)
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, resolve as resolvePath } from 'node:path';
import { fileURLToPath } from 'node:url';
import StyleDictionary from 'style-dictionary';
import { THEMES, validateTokens, resolve, cssValue, cssName } from './token-lib.mjs';
import { buildSymbolModule } from './symbol-lib.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const HEADER = 'Generated by packages/design-system/scripts/build-tokens.mjs from tokens/. Do not edit.';
const SCALE_GROUPS = ['space', 'radius', 'border-width'];
const sha = text => createHash('sha256').update(text).digest('hex');
const canonicalJSON = value => JSON.stringify(value, null, 2) + '\n';

/** Style Dictionary resolution of one theme; returns path -> resolved DTCG value. */
async function styleDictionaryResolve(files, theme) {
  const sd = new StyleDictionary({
    source: [...files.primitive, ...files.semantic, ...files.component, ...files.card, files.themes[theme]].map(f => join(root, f)),
    usesDtcg: true, log: { verbosity: 'silent', warnings: 'error' }, platforms: { raw: { transforms: ['name/kebab'] } },
  });
  await sd.hasInitialized;
  const { allTokens } = await sd.getPlatformTokens('raw');
  return new Map(allTokens.map(token => [token.path.join('.'), token.$value]));
}

const emitted = token => token.layer !== 'primitive' || SCALE_GROUPS.includes(token.path.split('.')[0]);
function declarations(token, value) {
  if (token.type === 'typography') {
    const parts = {
      'font-family': cssValue('fontFamily', value.fontFamily), 'font-size': cssValue('dimension', value.fontSize),
      'line-height': typeof value.lineHeight === 'number' ? String(value.lineHeight) : cssValue('dimension', value.lineHeight),
      'font-weight': cssValue('fontWeight', value.fontWeight), 'letter-spacing': cssValue('dimension', value.letterSpacing),
    };
    return [[cssName(token.path), `${parts['font-weight']} ${parts['font-size']}/${parts['line-height']} ${parts['font-family']}`], ...Object.entries(parts).map(([k, v]) => [`${cssName(token.path)}-${k}`, v])];
  }
  return [[cssName(token.path), cssValue(token.type, value, token)]];
}
const block = (selector, rows, extra = []) => `${selector} {\n${[...extra, ...rows.map(([name, value]) => `${name}: ${value};`)].map(line => '  ' + line).join('\n')}\n}\n`;

export async function buildTokens(outDir = join(root, 'src/generated')) {
  const { errors, sets, files } = validateTokens(root);
  if (errors.length) throw new Error('Token validation failed:\n' + errors.join('\n'));
  const resolved = {};
  for (const theme of THEMES) {
    const sd = await styleDictionaryResolve(files, theme), ours = new Map([...sets[theme].values()].map(t => [t.path, resolve(sets[theme], t.value)]));
    // Qualification: Style Dictionary must agree with the subset resolver for every token.
    for (const [path, value] of ours) if (JSON.stringify(sd.get(path)) !== JSON.stringify(value)) throw new Error(`Style Dictionary resolution differs for ${path} (${theme})`);
    if (sd.size !== ours.size) throw new Error(`Style Dictionary token count differs (${theme})`);
    resolved[theme] = ours;
  }
  const themeFile = theme => files.themes[theme];
  const tokens = [...sets.paper.values()].sort((a, b) => a.path.localeCompare(b.path));
  const shared = tokens.filter(t => t.file !== themeFile('paper') && emitted(t));
  const themed = tokens.filter(t => t.file === themeFile('paper'));
  const rows = (list, theme) => list.flatMap(t => declarations(t, resolved[theme].get(t.path)));
  const ms = path => resolved.paper.get(path).value;

  // tokens.css: shared values, Paper default, Ink by system preference or explicit choice, density and motion modes.
  const reduced = { hover: 0, menu: 0, dialog: ms('motion.fade'), 'binder-page': ms('motion.fade'), card: 0, major: 0, 'reward-beat-max': 0 };
  const css = [
    `/* ${HEADER} */\n`,
    block(':root', [...rows(shared, 'paper'), ...rows(themed, 'paper'),
      ['--is-row-height', 'var(--is-density-row-comfortable)'], ['--is-motion-distance-scale', '1']], ['color-scheme: light;']),
    `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme="paper"])', rows(themed, 'ink'), ['color-scheme: dark;']).replace(/^/gm, '  ').trimEnd()}\n}\n`,
    block(':root[data-theme="ink"]', rows(themed, 'ink'), ['color-scheme: dark;']),
    block(':root[data-density="compact"]', [['--is-row-height', 'var(--is-density-row-compact)']]),
    `@media (prefers-reduced-motion: reduce) {\n${block(':root', [...Object.entries(reduced).map(([k, v]) => [`--is-motion-${k}`, `${v}ms`]), ['--is-motion-distance-scale', '0']]).replace(/^/gm, '  ').trimEnd()}\n}\n`,
    block(':root[data-motion="reduced"]', [...Object.entries(reduced).map(([k, v]) => [`--is-motion-${k}`, `${v}ms`]), ['--is-motion-distance-scale', '0']]),
  ].join('\n');

  // layout.module.css: breakpoints as stylesheet values (CSS Modules @value), never runtime variables in media queries.
  const bp = name => resolved.paper.get('breakpoint.' + name);
  const width = d => `${d.value}${d.unit}`;
  const layout = [`/* ${HEADER} */`,
    `@value compact: (width < ${width(bp('intermediate'))});`,
    `@value intermediate: (${width(bp('intermediate'))} <= width < ${width(bp('wide'))});`,
    `@value atLeastIntermediate: (width >= ${width(bp('intermediate'))});`,
    `@value wide: (width >= ${width(bp('wide'))});`,
    `@value expanded: (width >= ${width(bp('expanded'))});`, ''].join('\n');

  // fonts.css: self-hosted interface and card-face faces plus measured fallback faces (standard §6, §7).
  const fonts = JSON.parse(readFileSync(join(root, 'src/assets/fonts/manifest.json'), 'utf8'));
  const url = path => `url("../${path.replace(/^src\//, '')}") format("woff2")`;
  const face = (family, f, extra = '') => `@font-face {\n  font-family: "${family}";\n  src: ${url(f.src ?? f.path)};\n  font-weight: ${f.weight};\n  font-style: ${f.style};\n  font-display: swap;${extra}\n}`;
  const adjusted = f => `\n  size-adjust: ${f.sizeAdjust}%;\n  ascent-override: ${f.ascentOverride}%;\n  descent-override: ${f.descentOverride}%;\n  line-gap-override: ${f.lineGapOverride}%;`;
  const imported = fonts.families.filter(f => f.status === 'imported');
  const fontCss = [`/* ${HEADER} Font provenance: src/assets/fonts/manifest.json */`,
    // Files marked with a `use` serve only the coverage fallback below, never the interface family.
    ...imported.flatMap(family => family.files.filter(f => !f.use).map(f => face(family.family, f))),
    ...fonts.fallback.faces.map(f => `@font-face {\n  font-family: "${fonts.fallback.family}";\n  src: ${f.local.map(n => `local("${n}")`).join(', ')};\n  font-weight: ${f.weight};\n  font-style: normal;${adjusted(f)}\n}`),
    ...fonts.card_text_fallback.faces.map(f => face(fonts.card_text_fallback.family, f, adjusted(f))), ''].join('\n');

  // tokens.ts: typed token names, values per theme and non-CSS values.
  const cssTokens = [...shared, ...themed];
  const names = Object.fromEntries(cssTokens.map(t => [t.path, cssName(t.path)]));
  const values = Object.fromEntries(THEMES.map(theme => [theme, Object.fromEntries(cssTokens.map(t => [t.path, t.type === 'typography' ? declarations(t, resolved[theme].get(t.path))[0][1] : cssValue(t.type, resolved[theme].get(t.path), t)]))]));
  const motionMs = Object.fromEntries(tokens.filter(t => t.path.startsWith('motion.') && t.layer === 'semantic' && t.type === 'duration').map(t => [t.path.slice(7), resolved.paper.get(t.path).value]));
  const ts = [`/* ${HEADER} */`,
    `export const themes = ${JSON.stringify(THEMES)} as const;`,
    'export type Theme = (typeof themes)[number];',
    `export const cssVariables = ${JSON.stringify(names, null, 2)} as const;`,
    'export type DesignToken = keyof typeof cssVariables;',
    '/** A CSS var() reference for a semantic, component, card or scale token. */',
    'export function cssVar(token: DesignToken): string { return `var(${cssVariables[token]})`; }',
    `export const themeValues: Record<Theme, Record<DesignToken, string>> = ${JSON.stringify(values, null, 2)};`,
    `export const breakpoints = ${JSON.stringify(Object.fromEntries(['intermediate', 'wide', 'expanded'].map(n => [n, width(bp(n))])), null, 2)} as const;`,
    `export const motionDurationsMs = ${JSON.stringify(motionMs, null, 2)} as const;`,
    `export const reducedMotionDurationsMs = ${JSON.stringify(reduced, null, 2)} as const;`, ''].join('\n');

  // renderer.ts: colours for Babylon with an explicit colour space; never converted twice.
  const toLinear = c => c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  const colorTokens = theme => Object.fromEntries(tokens.filter(t => t.type === 'color' && t.layer !== 'primitive').map(t => {
    const v = resolved[theme].get(t.path);
    return [t.path, { srgb: v.components.map(c => Number(c.toFixed(6))), linear: v.components.map(c => Number(toLinear(c).toFixed(6))), alpha: v.alpha ?? 1 }];
  }));
  const renderer = [`/* ${HEADER} */`,
    '/** srgb: gamma-encoded components (0-1) for APIs that take sRGB, such as Babylon Color3 used without linear conversion. linear: the same colour in linear light. Use exactly one. */',
    'export interface RendererColor { readonly srgb: readonly [number, number, number]; readonly linear: readonly [number, number, number]; readonly alpha: number }',
    `export const rendererColors: Record<${JSON.stringify(THEMES).replace(/[[\]]/g, '').replace(/,/g, ' | ')}, Record<string, RendererColor>> = ${JSON.stringify(Object.fromEntries(THEMES.map(t => [t, colorTokens(t)])), null, 2)};`, ''].join('\n');

  // manifest.json: documentation and drift identity.
  const symbolManifest = JSON.parse(readFileSync(join(root, 'src/assets/symbols/manifest.json'), 'utf8'));
  const sources = [...files.primitive, ...files.semantic, ...files.component, ...files.card, ...THEMES.map(themeFile), 'tokens/contrast-pairs.json', 'src/assets/fonts/manifest.json', 'src/assets/symbols/manifest.json', ...symbolManifest.symbols.map(s => s.path)];
  const manifest = {
    schema_version: 1, generator: 'packages/design-system/scripts/build-tokens.mjs', format: 'DTCG 2025.10 documented subset (see docs/runbooks/design-system.md)', resolver: 'style-dictionary 5.6.0',
    sources: sources.map(file => ({ file, sha256: sha(readFileSync(join(root, file))) })),
    tokens: tokens.map(t => ({ path: t.path, layer: t.layer, type: t.type, description: t.description, file: t.file, cssVariable: names[t.path] ?? null,
      values: Object.fromEntries(THEMES.map(theme => { const tok = sets[theme].get(t.path); return [theme, t.type === 'typography' ? declarations(tok, resolved[theme].get(t.path))[0][1] : cssValue(tok.type, resolved[theme].get(t.path), tok)]; })) })),
  };
  // Theme-only tokens are listed once with both values.
  mkdirSync(outDir, { recursive: true });
  const outputs = { 'tokens.css': css, 'layout.module.css': layout, 'fonts.css': fontCss, 'tokens.ts': ts, 'renderer.ts': renderer, 'symbols.ts': buildSymbolModule(root, HEADER.replace('from tokens/', 'from src/assets/symbols/')), 'manifest.json': canonicalJSON(manifest) };
  for (const [name, text] of Object.entries(outputs)) writeFileSync(join(outDir, name), text);
  return Object.keys(outputs);
}

if (process.argv[1] && resolvePath(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = process.argv[2] ? resolvePath(process.argv[2]) : undefined;
  buildTokens(out).then(names => console.log('PASS token build: ' + names.join(', '))).catch(error => { console.error(error.message); process.exitCode = 1; });
}
