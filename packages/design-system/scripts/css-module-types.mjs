// Generates exact class-name types for every CSS module (Name.module.d.css.ts beside Name.module.css),
// so a misspelled class is a type error. Usage: node scripts/css-module-types.mjs [--check]
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
export function moduleFiles(folder = join(root, 'src')) {
  const out = [];
  for (const name of readdirSync(folder)) {
    const path = join(folder, name);
    if (statSync(path).isDirectory()) { if (name !== 'generated') out.push(...moduleFiles(path)); } // generated layout values are consumed from CSS only
    else if (name.endsWith('.module.css')) out.push(path);
  }
  return out.sort();
}
export function classNames(css) {
  const text = css.replace(/\/\*[\s\S]*?\*\//g, '').replace(/"[^"]*"|'[^']*'/g, '""').replace(/@value[^;]*;/g, '');
  return [...new Set([...text.matchAll(/\.(-?[_a-zA-Z][_a-zA-Z0-9-]*)/g)].map(m => m[1]))].sort();
}
export function typesFor(path) {
  const names = classNames(readFileSync(path, 'utf8'));
  return `// Generated by packages/design-system/scripts/css-module-types.mjs from ${path.split('/').pop()}. Do not edit.\ndeclare const styles: {\n${names.map(n => `  readonly ${/^[a-zA-Z_$][\w$]*$/.test(n) ? n : JSON.stringify(n)}: string;`).join('\n')}\n};\nexport default styles;\n`;
}
export function writeTypes({ check = false } = {}) {
  const stale = [];
  for (const path of moduleFiles()) {
    const target = path.replace(/\.module\.css$/, '.module.d.css.ts'), text = typesFor(path);
    if (check) { if (!existsSync(target) || readFileSync(target, 'utf8') !== text) stale.push(relative(root, target)); }
    else writeFileSync(target, text);
  }
  return stale;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check'), stale = writeTypes({ check });
  if (stale.length) { console.error('Stale CSS module types: ' + stale.join(', ') + '. Run node scripts/css-module-types.mjs'); process.exitCode = 1; }
  else console.log(check ? 'PASS CSS module types current' : 'Wrote CSS module types');
}
